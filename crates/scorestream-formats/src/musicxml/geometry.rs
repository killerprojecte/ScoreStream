//! Explicit, finite geometry regeneration. Never a generic unknown-field filter.
use super::{read::decimal, xml::Node};
use crate::{Format, MappingEffect, MappingReport};
use scorestream_core::SourceRange;
use serde::{Deserialize, Serialize};

/// Input-only policy. No original positions are claimed to survive regeneration.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GeometryPolicy {
    #[default]
    Strict,
    /// Only direct measure/@width and note/@default-x, @default-y. Other geometry,
    /// semantic display fields, unknown elements and descendants remain blocking.
    RegenerateNoteAndMeasureCoordinates,
}
impl GeometryPolicy {
    pub(crate) fn is_strict(&self) -> bool {
        *self == Self::Strict
    }
}
#[derive(Clone, Copy)]
enum Field {
    MeasureWidth = 0,
    NoteX = 1,
    NoteY = 2,
}
impl Field {
    fn classify(n: &Node, key: &str) -> Option<Self> {
        // Paths are generated by the XML reader, never supplied by source text.
        // Match the entire ancestry so the policy cannot expand to another context.
        let path: Vec<_> = n
            .path
            .split('/')
            .filter(|s| !s.is_empty())
            .map(|s| s.split('[').next().unwrap_or(s))
            .collect();
        match (path.as_slice(), n.name.as_str(), key) {
            (["score-partwise", "part", "measure"], "measure", "width") => Some(Self::MeasureWidth),
            (["score-partwise", "part", "measure", "note"], "note", "default-x") => {
                Some(Self::NoteX)
            }
            (["score-partwise", "part", "measure", "note"], "note", "default-y") => {
                Some(Self::NoteY)
            }
            _ => None,
        }
    }
    fn name(self) -> &'static str {
        match self {
            Self::MeasureWidth => "measure/@width",
            Self::NoteX => "note/@default-x",
            Self::NoteY => "note/@default-y",
        }
    }
}
/// Constant-size accounting across the entire first pass, independent of report
/// truncation. The policy never changes the XML nodes or their source fingerprint.
#[derive(Default)]
pub(super) struct Audit {
    counts: [u64; 3],
    first: [Option<(String, SourceRange)>; 3],
}
impl Audit {
    /// true means the exact field was handled, including invalid-value diagnostics.
    /// It does not authorize accepting anything else on the node or below it.
    pub(super) fn attribute(
        &mut self,
        n: &Node,
        key: &str,
        policy: GeometryPolicy,
        report: &mut MappingReport,
    ) -> bool {
        if policy.is_strict() {
            return false;
        }
        let Some(field) = Field::classify(n, key) else {
            return false;
        };
        // Reuse the exact XML decimal lexical/precision boundary without cloning
        // a measure or note subtree just to validate one scalar attribute.
        let mut scalar = n.scalar_attribute(key);
        scalar.path.push_str(&format!("/@{key}"));
        // XML Schema decimal whitespace is XML whitespace only. Rust trim()
        // alone would silently accept NBSP and other Unicode spacing characters.
        if scalar
            .text
            .chars()
            .any(|c| c.is_whitespace() && !matches!(c, ' ' | '\t' | '\n' | '\r'))
        {
            scalar.error(
                report,
                MappingEffect::Invalid,
                "geometry.number_whitespace",
                "Geometry decimals allow only XML whitespace, not other Unicode spacing",
            );
            return true;
        }
        if let Err(errors) = decimal(&scalar) {
            report.append(errors);
            return true;
        }
        let i = field as usize;
        self.counts[i] += 1;
        self.first[i].get_or_insert((scalar.path, n.source));
        true
    }
    pub(super) fn prepend_report(self, report: MappingReport) -> MappingReport {
        let mut out = MappingReport::default();
        for field in [Field::MeasureWidth, Field::NoteX, Field::NoteY] {
            let i = field as usize;
            if let Some((path, source)) = self.first[i].as_ref() {
                out.push_source(Format::MusicXml, MappingEffect::PolicyApplied,
                    "geometry.regenerate_coordinates", path,
                    format!("Explicit regenerate_note_and_measure_coordinates policy: {} validated {} values encountered in the first pass. On successful import the original values are not retained; engraving must regenerate these positions. Failed import returns no partial document. Pitch, rhythm, visibility and other authored notation are not covered. This is not a whole-score acceptance result.", self.counts[i], field.name()),
                    Some(*source));
            }
        }
        // Appending through the bounded-report API keeps a blocking truncated
        // summary blocking even when these three policy records take its slots.
        out.append(report);
        out
    }
}
