//! Exact authored coordinate preservation or explicit regeneration. Never a generic unknown-field filter.
use super::{read::decimal, xml::Node};
use crate::{Format, MappingEffect, MappingReport};
use scorestream_core::SourceRange;
use serde::{Deserialize, Serialize};

/// Import chooses strict rejection, exact retention, or explicit, reported regeneration.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GeometryPolicy {
    #[default]
    Strict,
    /// Only direct measure/@width and note/@default-x, @default-y. Other geometry,
    /// semantic display fields, unknown elements and descendants remain blocking.
    RegenerateNoteAndMeasureCoordinates,
    /// Retain typed event/measure and ordered augmentation-dot coordinates without applying them to rendering.
    PreserveNoteAndMeasureCoordinates,
}
impl GeometryPolicy {
    pub(crate) fn is_strict(&self) -> bool {
        *self == Self::Strict
    }
}
#[derive(Clone, Copy)]
enum Field {
    MeasureWidth = 0,
    NoteX = 1,
    NoteY = 2,
    DotX = 3,
    DotY = 4,
}
impl Field {
    fn classify(n: &Node, key: &str) -> Option<Self> {
        // Paths are generated by the XML reader, never supplied by source text.
        // Match the entire ancestry so the policy cannot expand to another context.
        let path: Vec<_> = n
            .path
            .split('/')
            .filter(|s| !s.is_empty())
            .map(|s| s.split('[').next().unwrap_or(s))
            .collect();
        match (path.as_slice(), n.name.as_str(), key) {
            (["score-partwise", "part", "measure"], "measure", "width") => Some(Self::MeasureWidth),
            (["score-partwise", "part", "measure", "note"], "note", "default-x") => {
                Some(Self::NoteX)
            }
            (["score-partwise", "part", "measure", "note"], "note", "default-y") => {
                Some(Self::NoteY)
            }
            (["score-partwise", "part", "measure", "note", "dot"], "dot", "default-x") => {
                Some(Self::DotX)
            }
            (["score-partwise", "part", "measure", "note", "dot"], "dot", "default-y") => {
                Some(Self::DotY)
            }
            _ => None,
        }
    }
    fn name(self) -> &'static str {
        match self {
            Self::MeasureWidth => "measure/@width",
            Self::NoteX => "note/@default-x",
            Self::NoteY => "note/@default-y",
            Self::DotX => "note/dot/@default-x",
            Self::DotY => "note/dot/@default-y",
        }
    }
}
/// Constant-size accounting across the entire first pass, independent of report
/// truncation. The policy never changes the XML nodes or their source fingerprint.
#[derive(Default)]
pub(super) struct Audit {
    counts: [u64; 5],
    first: [Option<(String, SourceRange)>; 5],
    preserved: bool,
}
impl Audit {
    /// true means the exact field was handled, including invalid-value diagnostics.
    /// It does not authorize accepting anything else on the node or below it.
    pub(super) fn attribute(
        &mut self,
        n: &Node,
        key: &str,
        policy: GeometryPolicy,
        report: &mut MappingReport,
    ) -> bool {
        if policy.is_strict() {
            return false;
        }
        let Some(field) = Field::classify(n, key) else {
            return false;
        };
        // The older explicit regeneration policy covers only note/measure attrs.
        if matches!(field, Field::DotX | Field::DotY)
            && policy != GeometryPolicy::PreserveNoteAndMeasureCoordinates
        {
            return false;
        }
        // Check exact XML decimal syntax without cloning
        // a measure or note subtree just to validate one scalar attribute.
        let mut scalar = n.scalar_attribute(key);
        scalar.path.push_str(&format!("/@{key}"));
        // XML Schema decimal whitespace is XML whitespace only. Rust trim()
        // alone would silently accept NBSP and other Unicode spacing characters.
        if scalar
            .text
            .chars()
            .any(|c| c.is_whitespace() && !matches!(c, ' ' | '\t' | '\n' | '\r'))
        {
            scalar.error(
                report,
                MappingEffect::Invalid,
                "geometry.number_whitespace",
                "Geometry decimals allow only XML whitespace, not other Unicode spacing",
            );
            return true;
        }
        if let Err(errors) = if policy == GeometryPolicy::PreserveNoteAndMeasureCoordinates {
            exact_decimal(&scalar)
        } else {
            decimal(&scalar)
        } {
            report.append(errors);
            return true;
        }
        self.preserved = policy == GeometryPolicy::PreserveNoteAndMeasureCoordinates;
        let i = field as usize;
        self.counts[i] += 1;
        self.first[i].get_or_insert((scalar.path, n.source));
        true
    }
    pub(super) fn prepend_report(self, report: MappingReport) -> MappingReport {
        let mut out = MappingReport::default();
        for field in [
            Field::MeasureWidth,
            Field::NoteX,
            Field::NoteY,
            Field::DotX,
            Field::DotY,
        ] {
            let i = field as usize;
            if let Some((path, source)) = self.first[i].as_ref() {
                out.push_source(Format::MusicXml, if self.preserved { MappingEffect::Preserved } else { MappingEffect::PolicyApplied },
                    if self.preserved { "geometry.preserved_coordinates" } else { "geometry.regenerate_coordinates" }, path,
                    if self.preserved { format!("Validated {} authored {} values in the first pass. Successful import retains their exact decimal tenths; a failed import returns no score. Preview engraves independently.", self.counts[i], field.name()) } else { format!("Explicit regenerate_note_and_measure_coordinates policy: {} validated {} values encountered in the first pass. On successful import the original values are not retained; engraving must regenerate these positions. Failed import returns no partial document. Pitch, rhythm, visibility and other authored notation are not covered. This is not a whole-score acceptance result.", self.counts[i], field.name()) },
                    Some(*source));
            }
        }
        // Appending through the bounded-report API keeps a blocking truncated
        // summary blocking even when these policy records take its slots.
        out.append(report);
        out
    }
}

pub(super) fn event(
    n: &Node,
    id: &str,
    policy: GeometryPolicy,
) -> Result<Vec<scorestream_core::geometry::Geometry>, MappingReport> {
    use scorestream_core::geometry::Geometry;
    if policy != GeometryPolicy::PreserveNoteAndMeasureCoordinates {
        return Ok(vec![]);
    }
    let coordinates = |node: &Node| -> Result<_, MappingReport> {
        Ok((
            node.attr("default-x")
                .map(|_| exact_decimal(&node.scalar_attribute("default-x")))
                .transpose()?,
            node.attr("default-y")
                .map(|_| exact_decimal(&node.scalar_attribute("default-y")))
                .transpose()?,
        ))
    };
    let mut values = vec![];
    let (default_x, default_y) = coordinates(n)?;
    if default_x.is_some() || default_y.is_some() {
        values.push(Geometry::Event {
            event: id.into(),
            default_x,
            default_y,
        });
    }
    for (index, dot) in n.children_named("dot").enumerate() {
        let (default_x, default_y) = coordinates(dot)?;
        if default_x.is_some() || default_y.is_some() {
            values.push(Geometry::Dot {
                event: id.into(),
                index: u32::try_from(index).map_err(|_| {
                    super::read::error(
                        dot,
                        "geometry.dot_index",
                        "Dot index exceeds the written-duration representation",
                    )
                })?,
                default_x,
                default_y,
            });
        }
    }
    Ok(values)
}
pub(super) struct Export {
    events: std::collections::BTreeMap<String, String>,
    dots: std::collections::BTreeMap<(String, u32), String>,
    measures: std::collections::BTreeMap<(String, String), String>,
}
impl Export {
    pub(super) fn new(score: &scorestream_core::score::ScoreDocument) -> Self {
        let mut result = Self {
            events: Default::default(),
            dots: Default::default(),
            measures: Default::default(),
        };
        for g in &score.geometry {
            match g {
                scorestream_core::geometry::Geometry::Event {
                    event,
                    default_x,
                    default_y,
                } => {
                    let mut attrs = String::new();
                    for (name, value) in [("default-x", default_x), ("default-y", default_y)] {
                        if let Some(value) = value {
                            attrs.push_str(&format!(
                                " {name}=\"{}\"",
                                decimal_text(value).expect("validated decimal")
                            ));
                        }
                    }
                    result.events.insert(event.clone(), attrs);
                }
                scorestream_core::geometry::Geometry::Dot {
                    event,
                    index,
                    default_x,
                    default_y,
                } => {
                    let mut attrs = String::new();
                    for (name, value) in [("default-x", default_x), ("default-y", default_y)] {
                        if let Some(value) = value {
                            attrs.push_str(&format!(
                                " {name}=\"{}\"",
                                decimal_text(value).expect("validated decimal")
                            ));
                        }
                    }
                    result.dots.insert((event.clone(), *index), attrs);
                }
                scorestream_core::geometry::Geometry::Measure {
                    part,
                    measure,
                    width,
                } => {
                    result.measures.insert(
                        (part.clone(), measure.clone()),
                        format!(
                            " width=\"{}\"",
                            decimal_text(width).expect("validated decimal")
                        ),
                    );
                }
            }
        }
        result
    }
    pub(super) fn event(&self, id: &str) -> &str {
        self.events.get(id).map(String::as_str).unwrap_or("")
    }
    pub(super) fn dot(&self, id: &str, index: u32) -> &str {
        self.dots
            .get(&(id.into(), index))
            .map(String::as_str)
            .unwrap_or("")
    }
    pub(super) fn measure(&self, part: &str, id: &str) -> &str {
        self.measures
            .get(&(part.into(), id.into()))
            .map(String::as_str)
            .unwrap_or("")
    }
}

pub(super) fn exact_decimal(n: &Node) -> Result<scorestream_core::Rational, MappingReport> {
    use num_bigint::BigInt;
    use scorestream_core::Rational;
    let value = n.text.trim_matches([' ', '\t', '\n', '\r']);
    let signed = value.strip_prefix(['+', '-']).unwrap_or(value);
    let (whole, fraction) = signed.split_once('.').unwrap_or((signed, ""));
    if (whole.is_empty() && fraction.is_empty())
        || !whole.bytes().all(|b| b.is_ascii_digit())
        || !fraction.bytes().all(|b| b.is_ascii_digit())
    {
        return Err(super::read::error(
            n,
            "geometry.decimal",
            "Expected exact XML decimal tenths",
        ));
    }
    let digits = format!("{whole}{fraction}")
        .parse::<BigInt>()
        .map_err(|_| super::read::error(n, "geometry.decimal", "Invalid decimal tenths"))?;
    let denominator = format!("1{}", "0".repeat(fraction.len()))
        .parse::<BigInt>()
        .expect("decimal power");
    Ok(&Rational::from_big_integer(if value.starts_with('-') {
        -digits
    } else {
        digits
    }) / &Rational::from_big_integer(denominator))
}
pub(crate) fn decimal_text(value: &scorestream_core::Rational) -> Option<String> {
    use num_bigint::BigInt;
    let mut denominator = value.denominator().clone();
    let mut scale = 0usize;
    while &denominator % 2u8 == BigInt::from(0) {
        denominator /= 2u8;
        scale += 1;
    }
    let mut fives = 0usize;
    while &denominator % 5u8 == BigInt::from(0) {
        denominator /= 5u8;
        fives += 1;
    }
    if denominator != BigInt::from(1) {
        return None;
    }
    scale = scale.max(fives);
    let power = format!("1{}", "0".repeat(scale)).parse::<BigInt>().ok()?;
    let numerator = value.numerator() * power / value.denominator();
    let raw = numerator.to_string();
    let (sign, digits) = raw
        .strip_prefix('-')
        .map(|s| ("-", s))
        .unwrap_or(("", raw.as_str()));
    if scale == 0 {
        return Some(raw);
    }
    let padded = format!(
        "{}{}",
        "0".repeat((scale + 1).saturating_sub(digits.len())),
        digits
    );
    let split = padded.len() - scale;
    let result = format!("{sign}{}.{}", &padded[..split], &padded[split..]);
    Some(
        result
            .trim_end_matches('0')
            .trim_end_matches('.')
            .to_string(),
    )
}
