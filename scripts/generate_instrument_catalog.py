#!/usr/bin/env python3
"""Generate the desktop catalog from the format-neutral core source. No dependencies."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/scorestream-core/src/instruments/catalog.json"
TARGET = ROOT / "desktop/src/instruments/catalog.ts"
FAMILIES = {"strings", "woodwinds", "brass", "plucked_strings", "keyboards",
            "pitched_percussion", "unpitched_percussion"}


def generate():
    catalog = json.loads(SOURCE.read_text())
    seen = set()
    for entry in catalog:
        assert set(entry) == {"id", "name", "family", "pitch_kind", "aliases"}
        assert entry["name"] and entry["family"] in FAMILIES
        assert entry["pitch_kind"] in {"pitched", "unpitched"}
        for key in [entry["id"], *entry["aliases"]]:
            assert key and all(c in "abcdefghijklmnopqrstuvwxyz_-" for c in key), key
            assert key not in seen, key
            seen.add(key)
    rows = ",\n".join(" " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in catalog)
    return """// Generated by scripts/generate_instrument_catalog.py. Edit the core catalog instead.
export type InstrumentFamily = 'strings'|'woodwinds'|'brass'|'plucked_strings'|'keyboards'|'pitched_percussion'|'unpitched_percussion';
export interface InstrumentDefinition {
 readonly id:string; readonly name:string; readonly family:InstrumentFamily;
 readonly pitch_kind:'pitched'|'unpitched'; readonly aliases:readonly string[];
}
export const INSTRUMENT_CATALOG = [
""" + rows + """
] as const satisfies readonly InstrumentDefinition[];
export type StandardInstrumentId = typeof INSTRUMENT_CATALOG[number]['id'];
export type StandardInstrument = typeof INSTRUMENT_CATALOG[number];

const identities = new Map<string,StandardInstrument>();
for(const instrument of INSTRUMENT_CATALOG){
 identities.set(instrument.id,instrument);
 for(const alias of instrument.aliases)identities.set(alias,instrument);
}
/** Exact identity lookup only. Never rewrites source or implies transposition. */
export function resolveInstrument(id:string):StandardInstrument|null {
 return identities.get(id)??null;
}
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    content = generate()
    if options.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit("Desktop instrument catalog is stale. Run scripts/generate_instrument_catalog.py")
        print("Instrument catalog contract and generated desktop definitions match.")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content)
